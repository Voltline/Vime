#!/usr/bin/env python3
"""Lists Chinese names of works and characters from a Bangumi wiki dump.

    python3 Scripts/collect_bangumi_terms.py <bangumi-YYYY-MM-DD.zip> [--out Scripts/rime_bangumi.txt]

The dump is the weekly export at https://github.com/bangumi/Archive/releases
(subject.jsonlines, character.jsonlines and subject-characters.jsonlines).
Bangumi publishes entry and character information under CC BY-SA 3.0
(https://bgm.tv/about/copyright).

A work gives its Chinese title (name_cn), a character its 简体中文名. Each
name splits at punctuation, symbols, spaces and the middle dot (鲁路修·兰佩路基
gives 鲁路修 and 兰佩路基). A part keeps its Chinese characters when it has
two to ten and nothing else but a trailing number (合金弹头7 gives 合金弹头);
a part mixing in kana or Latin letters (1只外星猫) is left out whole, so no
fragment of a title is listed. A work keeps only the first such part, its
main title: later parts are seasons and the clauses of long light-novel
titles (进击的巨人 第二季 gives 进击的巨人); a season written into the
title is dropped too (丁丁历险记第二季 gives 丁丁历险记). NSFW works are
skipped, and so are works users tag as adult (ADULT_TAGS) and characters
that appear in no other work.

A name's popularity is the number of users who collected it (a work's wish,
done, doing, on-hold and dropped counts); a name several entries give keeps
the highest. The output lists one name per line with its popularity, sorted
by name, leaving out names nobody collected; Scripts/build_rime_dicts.py
reads it, reads each name like any other word and skips the names it
already has.
"""
import argparse
import io
import json
import re
import unicodedata
import zipfile
from pathlib import Path

HAN = re.compile("[\\u3400-\\u4dbf\\u4e00-\\u9fff]+")
TRAILING_NUMBER = re.compile("[0-9\\uff10-\\uff19\\u2160-\\u217f]+$")
# A season or part written into the title itself (丁丁历险记第二季).
TRAILING_SEASON = re.compile("第[0-9一二三四五六七八九十]+[季期部章]$")
MIN_LENGTH, MAX_LENGTH = 2, 10
INFOBOX_NAME = re.compile(r"^\|简体中文名\s*=\s*(.+?)\s*$", re.M)
# Tags that mark adult works the NSFW flag misses, when at least two users gave them.
ADULT_TAGS = {"R18", "18禁", "拔作", "里番", "3D里番", "黄油", "工口", "本子", "成人", "成人漫画", "成年コミック",
              "アダルトコミック", "韩漫R", "HRPG", "凌辱", "调教", "NTR"}


def parts(name):
    """The name's parts that are Chinese characters only, within the length limits."""
    found, part = [], []
    for char in (name or "") + " ":
        if unicodedata.category(char)[0] in "PSZC":
            text = TRAILING_SEASON.sub("", TRAILING_NUMBER.sub("", "".join(part)))
            if HAN.fullmatch(text) and MIN_LENGTH <= len(text) <= MAX_LENGTH:
                found.append(text)
            part = []
        else:
            part.append(char)
    return found


def records(archive, member):
    with archive.open(member) as raw:
        for line in io.TextIOWrapper(raw, encoding="utf-8"):
            if line.strip():
                yield json.loads(line)


def collect(path):
    names = {}

    def add(name, popularity, first_only=False):
        for part in parts(name)[:1] if first_only else parts(name):
            names[part] = max(names.get(part, 0), popularity)

    with zipfile.ZipFile(path) as archive:
        allowed = set()
        for subject in records(archive, "subject.jsonlines"):
            if subject.get("nsfw") or any(tag["name"] in ADULT_TAGS and tag.get("count", 0) >= 2
                                          for tag in subject.get("tags") or []):
                continue
            allowed.add(subject["id"])
            add(subject.get("name_cn"), sum((subject.get("favorite") or {}).values()), first_only=True)
        appears = {link["character_id"] for link in records(archive, "subject-characters.jsonlines")
                   if link["subject_id"] in allowed}
        for character in records(archive, "character.jsonlines"):
            if character["id"] not in appears:
                continue
            found = INFOBOX_NAME.search(character.get("infobox") or "")
            if found:
                add(found.group(1), character.get("collects") or 0)
    return {name: popularity for name, popularity in names.items() if popularity >= 1}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("dump", type=Path)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("rime_bangumi.txt"))
    args = parser.parse_args()
    names = collect(args.dump)
    with args.out.open("w", encoding="utf-8") as out:
        out.write(f"# Chinese names of works and characters from the Bangumi wiki dump {args.dump.name},\n"
                  "# CC BY-SA 3.0 (https://bgm.tv/about/copyright). Generated by\n"
                  "# Scripts/collect_bangumi_terms.py: the name, a tab, how many users collected it.\n")
        for name in sorted(names):
            out.write(f"{name}\t{names[name]}\n")
    print(f"{len(names)} names collected at least once")


if __name__ == "__main__":
    main()

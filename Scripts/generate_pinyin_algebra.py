# Letters next to each other on a QWERTY row, as in librime's corrector.cc.
ROWS = ["qwertyuiop", "asdfghjkl", "zxcvbnm"]
# Corrections, at log(0.01) each, that a typo spelling another valid syllable
# carries.
TIER2_CORRECTIONS = 5


def neighbours():
    pairs = []
    for row in ROWS:
        for i, letter in enumerate(row):
            for j in (i - 1, i + 1):
                if 0 <= j < len(row):
                    pairs.append((letter, row[j]))
    return pairs


def u_spellings(syllable):
    """The spellings the ü rules derive from a syllable."""
    result = {syllable}
    result.add(re.sub(r"^([nl])ve$", r"\1ue", syllable))
    result.add(re.sub(r"^([jqxy])u", r"\1v", syllable))
    return result


def rules():
    syllables = set(SYLLABLES)
    assert len(syllables) == len(SYLLABLES)
    # Letters that occur twice in some syllable need a rule for the last
    # occurrence as well as the first.
    repeated = {c for s in syllables for c in s if s.count(c) > 1}
    longest = max(map(len, syllables))
    spellings = sorted({x for s in syllables for x in u_spellings(s)}, key=lambda s: (len(s), s))
    prefixes = {}
    for s in syllables:
        for n in range(2, len(s)):
            p = s[:n]
            if p not in syllables and p not in ("zh", "ch", "sh"):
                prefixes.setdefault(n, set()).add(p)

    out = ["# Not syllables on their own in Vime's dictionaries."]
    out += [f"erase/^{s}$/" for s in ("hm", "m", "n", "ng")]
    out.append("# 1. One-letter typos of syllables of 3+ letters, kept apart as \"x~\" for now.")
    for a, b in neighbours():
        out.append(f"derive/^([a-z]*?){a}([a-z]*)$/$1{b}$2~/correction")
        if a in repeated:
            out.append(f"derive/^([a-z]*){a}([a-z]*)$/$1{b}$2~/correction")
    for k in range(longest - 1):
        out.append(f"derive/^([a-z]{{{k}}})([a-z])([a-z])([a-z]*)$/$1$3$2$4~/correction")
    # Typos of one or two letters would hit everywhere; vowelless ones would
    # read initials (hsn) as a word.
    out.append("erase/^[a-z]{1,2}~$/")
    out.append("erase/^[bcdfghjklmnpqrstwxyz]+~$/")
    # No syllable starts with i, u or v; such keys would only make odd joints.
    out.append("erase/^[iuv][a-z]*~$/")
    out.append("# 2. Abbreviations: the initial, and unfinished syllables of 2+ letters.")
    out.append("abbrev/^([a-z])[a-z]+$/$1/")
    out.append("abbrev/^([zcs]h)[a-z]+$/$1/")
    for n in sorted(prefixes):
        out.append(f"abbrev/^({'|'.join(sorted(prefixes[n]))})[a-z]+$/$1/")
    out.append("# 3. ü spellings.")
    out += [
        "derive/^([nl])ve$/$1ue/",
        "derive/^([jqxy])u([a-z]*)$/$1v$2/",
        "derive/^([nl])ue$/$1ve/",
        "derive/^([jqxy])v([a-z]*)$/$1u$2/",
    ]
    out.append("# 4. A typo that spells a valid syllable takes four more correction")
    out.append("# penalties (log(1e-10) in all), below other corrections; the rest become keys.")
    alternatives = "|".join(spellings)
    out.append(f"derive/^({alternatives})~$/$1~~/correction")
    for n in range(2, TIER2_CORRECTIONS - 1):
        out.append(f"derive/^([a-z]+){'~' * n}$/$1{'~' * (n + 1)}/correction")
    out.append(f"derive/^([a-z]+){'~' * (TIER2_CORRECTIONS - 1)}$/$1/correction")
    out.append("erase/^[a-z]+~~+$/")
    out.append(f"erase/^({alternatives})~$/")
    out.append("xform/^([a-z]+)~$/$1/")
    return out


def render():
    lines = [BEGIN]
    for rule in rules():
        if rule.startswith("#"):
            lines.append(f"    {rule}")
        else:
            lines.append(f"    - {rule}")
    lines.append(END)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the schema is out of date")
    args = parser.parse_args()
    text = SCHEMA.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    updated = text[:start] + render() + text[end:]
    if args.check:
        if updated != text:
            sys.exit(f"{SCHEMA} is out of date; run {Path(__file__).name}")
        return
    SCHEMA.write_text(updated)
    print(f"wrote {len(rules())} lines of algebra to {SCHEMA.name}")


if __name__ == "__main__":
    main()
